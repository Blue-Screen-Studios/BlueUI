static const unsigned char kBox[7] = {0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f}; /* (a character it hasn't) */

static const unsigned char* glyph(char c) {
  if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
  if (c < 32 || c > 126 || kFont[c - 32][0] == 0xff) return NULL;
  return kFont[c - 32];
}

bool bui_has_glyph(char c) { return glyph(c) != NULL; }

const unsigned char* bui_glyph_rows(char c) {
  const unsigned char* g = glyph(c);
  return g ? g : kBox;
}

/* One pass of the text (its shadow's, or its own): its runs of lit pixels. */
static size_t pass(const char* text, size_t len, float x, float y, float pixel, float ox, float oy, bui_color c, bui_draw_cmd* out,
                   size_t at, size_t cap) {
  float cx = x, cy = y;
  for (size_t i = 0; i < len; ++i) {
    const char ch = text[i];
    if (ch == '\n') {
      cx = x, cy += BUI_LINE_ADVANCE * pixel;
      continue;
    }
    const unsigned char* g = bui_glyph_rows(ch);
    for (int row = 0; row < BUI_GLYPH_H; ++row)
      for (int col = 0; col < BUI_GLYPH_W;) {
        if (!(g[row] >> (BUI_GLYPH_W - 1 - col) & 1)) {
          ++col;
          continue;
        }
        int end = col;
        while (end < BUI_GLYPH_W && (g[row] >> (BUI_GLYPH_W - 1 - end) & 1)) ++end;
        if (at < cap) {
          const float x0 = cx + (float)col * pixel + ox, y0 = cy + (float)row * pixel + oy;
          const bui_draw_cmd r = {x0, y0, x0 + (float)(end - col) * pixel, y0 + pixel, c.r, c.g, c.b, c.a, 0, 0, 0, 0};
          out[at] = r;
        }
        ++at;
        col = end;
      }
    cx += BUI_GLYPH_ADVANCE * pixel;
  }
  return at;
}

size_t bui_text_rects(const char* text, size_t len, float x, float y, float pixel, bui_color color, float shadow, bui_draw_cmd* out,
                      size_t cap) {
  text = bui__s(text);
  if (len == BUI_NUL) len = strlen(text);
  size_t n = 0;
  if (shadow > 0.0f) n = pass(text, len, x, y, pixel, pixel, pixel, bui_rgba(0.0f, 0.0f, 0.0f, color.a * shadow), out, n, cap);
  return pass(text, len, x, y, pixel, 0.0f, 0.0f, color, out, n, cap);
}

void bui_text(bui_context* ui, const char* text, float x, float y, float pixel, bui_color color, float shadow) {
  bui_draw_cmd buf[256];
  const size_t n = bui_text_rects(text, BUI_NUL, x, y, pixel, color, shadow, buf, 256);
  if (n <= 256) {
    bui_draw(ui, buf, n);
    return;
  }
  bui_draw_cmd* big = malloc(n * sizeof(bui_draw_cmd));
  if (!big) return;
  bui_text_rects(text, BUI_NUL, x, y, pixel, color, shadow, big, n);
  bui_draw(ui, big, n);
  free(big);
}

float bui_text_width(const char* text, size_t len, float pixel) {
  text = bui__s(text);
  if (len == BUI_NUL) len = strlen(text);
  size_t longest = 0, line = 0;
  for (size_t i = 0; i < len; ++i) {
    line = text[i] == '\n' ? 0 : line + 1;
    if (line > longest) longest = line;
  }
  return longest == 0 ? 0.0f : ((float)longest * BUI_GLYPH_ADVANCE - 1.0f) * pixel;
}
